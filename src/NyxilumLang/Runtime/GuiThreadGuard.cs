// GuiThreadGuard.cs — недоступно поза Windows (як і GraphicsModule.cs),
// тому весь файл під #if WINDOWS; на Linux/Mac GUI-функції взагалі не
// реєструються, тож і охороняти нічого.
#if WINDOWS
using System.Windows.Forms;

namespace NyxilumLang.Runtime;

// Windows Forms вимагає, щоб контроли створювались і чіпались лише з
// того самого потоку, який їх створив (STA UI-потік) — інакше поведінка
// непередбачувана: від тихого пошкодження стану до крашу процесу.
// spawn() (ConcurrencyModule.cs) запускає код на НОВОМУ потоці — якщо
// такий воркер спробує оновити GUI, створений у головному потоці (типова
// помилка: "хай воркер порахує щось і сам оновить текст на екрані"),
// InvokeRequired ловить це одразу з чіткою NyxilumLang-помилкою замість
// непередбачуваного крашу чи мовчазного пошкодження стану контролу.
//
// Не охороняє СТВОРЕННЯ нових контролів (guiWindow/guiButton/...) —
// там інша проблема (STA apartment самого потоку), яку .NET діагностує
// сам; це навмисно вужчий, перевірений патерн: лише доступ до вже
// існуючого контролу з чужого потоку.
internal static class GuiThreadGuard
{
    public static void Ensure(Control control)
    {
        if (control.InvokeRequired)
            throw new Exception(
                "GUI-функції можна викликати лише з головного потоку, не з воркера (spawn) — " +
                "Windows Forms вимагає, щоб контроли чіпав лише той потік, який їх створив.");
    }
}
#endif
